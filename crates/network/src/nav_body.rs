//! Тело навигационного запроса — то, что оболочка отправляет вместе с
//! навигацией, а не только скачивает: отправка HTML-формы методом POST
//! (HTML LS §4.10.21.4, шаг 23 «submit as entity body»).
//!
//! Отдельный публичный тип, а не крейт-приватный `RequestBody`: последний
//! одалживает свои поля (`&'a str` / `&'a [u8]`) у вызывающего и живёт ровно
//! один запрос, тогда как оболочке нужно **владеть** телом — оно едет с
//! UI-потока в поток загрузки внутри `PageSource` и обязано пережить и
//! спавн потока, и цепочку редиректов. Превращение во внутренний
//! `RequestBody` происходит на границе [`crate::HttpClient::fetch_page`] /
//! [`crate::HttpClient::fetch_page_streaming`], так что путь запроса (куки,
//! HSTS, ad-block, HTTP/2, редиректы по Fetch §4.4) остаётся ровно тем же,
//! что у GET-навигации.

/// Метод, `Content-Type` и байты тела навигационного запроса.
///
/// Метод хранится строкой, а не enum-ом: единственный, кто его сегодня
/// заполняет, — отправка формы (`POST`), но по Fetch §4.4 шаг 11 редирект
/// может метод *сменить* (303 → GET), и решение об этом принимает сетевой
/// слой ниже по стеку, разбирая ту же строку, что и для fetch()-запросов
/// из JS. Заводить здесь свой enum значило бы держать второй словарь
/// методов рядом с существующим.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct NavigationBody {
    /// HTTP-метод запроса в верхнем регистре (`POST`).
    pub method: String,
    /// Значение заголовка `Content-Type` (`application/x-www-form-urlencoded`
    /// или `multipart/form-data; boundary=…` для отправки формы).
    pub content_type: String,
    /// Сырые байты тела — уже закодированный набор полей формы.
    pub bytes: Vec<u8>,
}

impl NavigationBody {
    /// Тело POST-навигации с заданным `Content-Type`.
    ///
    /// Метод фиксируется как `POST`: это единственный не-GET метод, которым
    /// умеет навигировать HTML-форма (`method="post"`; `dialog` не сетевой,
    /// всё прочее значение атрибута спека трактует как GET).
    pub fn post(content_type: impl Into<String>, bytes: Vec<u8>) -> Self {
        Self { method: "POST".to_owned(), content_type: content_type.into(), bytes }
    }
}
