//! Build-time linker configuration for the lumen shell.
//!
//! BUG-987: главный поток процесса выполняет рекурсивные обходы дерева боксов
//! по глубине DOM (синхронный relayout после правки <style>, style-снимки,
//! сериализаторы dump/print-режимов). Дефолтный PE-резерв стека main-потока —
//! 1 МБ (SizeOfStackReserve), и глубокие страницы (fandom.com + OneTrust,
//! корпус «топ-100») переполняют его уже на нескольких сотнях уровней
//! вложенности. Резерв 128 МБ поднимает порог до десятков тысяч уровней
//! (замер: обходы тратят ~1–7 КБ стека на уровень — сами кадры жирные, см.
//! задачу на итеративный обход в BUG-987). Расход — только виртуальная
//! память (коммит по-прежнему постраничный). Задача на итеративный обход
//! вместо рекурсии заведена отдельно (см. BUG-987).
//!
//! BUG-1027: этот флаг — **только** для Windows, и `#[cfg]` ниже говорит
//! ровно это. На Unix размер стека главного потока задаёт `RLIMIT_STACK`,
//! а не заголовок ELF, поэтому там тот же резерв даёт поток `lumen-main`,
//! на который `main()` уводит всю работу (`main.rs`,
//! `lumen_core::run_on_deep_stack`). Не считать эту строку
//! кроссплатформенной: после фикса BUG-987 Linux-сборка жила со штатными
//! 8 МиБ и падала на 200 вложенных `<div>`.
fn main() {
    #[cfg(target_os = "windows")]
    println!("cargo:rustc-link-arg=/STACK:134217728");
}
