fn lookup(table: &[(u32, u32)], ch: char) -> Option<char> {
    let key = ch as u32;
    table.binary_search_by_key(&key, |&(from, _)| from).ok().and_then(|i| char::from_u32(table[i].1))
}

/// `full-width`: символ → его полноширинная форма; U+0020 → U+3000.
pub fn full_width(ch: char) -> char {
    lookup(&FULL_WIDTH, ch).unwrap_or(ch)
}

/// `full-size-kana`: малая кана → полноразмерная.
pub fn full_size_kana(ch: char) -> char {
    lookup(&FULL_SIZE_KANA, ch).unwrap_or(ch)
}

/// `math-auto`: символ → математический курсив (`None`, если для него нет отображения).
pub fn math_italic(ch: char) -> Option<char> {
    lookup(&MATH_ITALIC, ch)
}
