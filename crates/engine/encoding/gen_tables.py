#!/usr/bin/env python3
"""Генерация таблиц однобайтовых кодировок и меток WHATWG Encoding Standard.

Пишет:
  src/tables/single_byte.rs — byte 0x80..0xFF -> char для всех однобайтовых кодировок;
  src/tables/labels.rs      — label -> Encoding по encodings.json (§4.2).

Источники скачиваются с https://encoding.spec.whatwg.org/ (index-<name>.txt,
encodings.json); репозиторий хранит только результат. Запуск из каталога
crates/engine/encoding:  python gen_tables.py
"""
