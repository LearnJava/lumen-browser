#!/usr/bin/env python3
"""WPT-RUN-5 slice 30: what does [BUG-796](../../bugs/BUG-796-FIXED.md) cost the number?

Slice 29 found the defect and bounded its *reach*: `meta.content` answers
`undefined` in our engine (a template getter on the element wrapper shadows the
reflecting one), `testharness.js::test_timeout` picks the file-level ceiling by
`metas[i].content === "long"`, so every one of the corpus's 8 196 `timeout: long`
ids is judged by the 10-second default instead of the 60-second one it declared.
What slice 29 did *not* measure is the price: a test cut off at 10 s is only a
false TIMEOUT if it would have finished inside 60 s, and nothing so far has asked
it.

This audit asks it directly, per test, with an A/B on the same binary:

* **arm A** — the page exactly as the corpus run got it;
* **arm B** — the same page with a shim injected immediately before its
  `testharness.js` include, redefining `content` on every `<meta>` already
  parsed (the shadowing property is `configurable: true`, verified live, so a
  plain `Object.defineProperty` is enough). Nothing else changes: the harness
  still runs at `timeout_multiplier: 1`, so arm B is "BUG-796 fixed", not "more
  time for everyone".

The arms are compared on the same scoring rule the published number uses
(`run_corpus.py::score_reports`: passing subtests over total, or 1.0 for a
subtest-less PASS), so the sample's mean score delta projects straight onto the
population as pass-rate points.

Two things this deliberately does not do. It does not run `wptrunner`: the
corpus run owns the pinned `config.json` ports, and a second runner would either
fight it for them or — worse, see the `StaticHandler` freeze in `CLAUDE.md` —
silently inherit the live run's substituted `--timeout-multiplier`. Pages are
served from a private static server instead, the way `inert_style_audit.py` and
`blank_render_audit.py` do. And it does not touch ids that server cannot serve
faithfully: `.any.*`/`.window.html` (generated by wptserve from a `.js`),
`.sub.` (needs substitution) and anything pulling in `testdriver.js` (needs
wptrunner's message queue) are counted and named, never silently sampled.

Usage (from repo root, venv per tests/wpt/README.md):

    <venv>/python tests/wpt/long_timeout_audit.py --census
    <venv>/python tests/wpt/long_timeout_audit.py --sample 40 --jobs 3 --json OUT
    <venv>/python tests/wpt/long_timeout_audit.py --selftest
"""

