def long_ids(manifest: dict) -> set:
    """Automatable ids the manifest declares `timeout: long`."""
    out = set()
    for test_type, _category, test_id, extras in corpus_stats.iter_entries(manifest):
        if test_type in corpus_stats.NON_AUTOMATABLE_TYPES:
            continue
        if extras.get("timeout") == "long":
            out.add(test_id)
    return out


def load_verdicts(out_dir: str) -> dict:
    """`{test_id: {"status", "seconds", "subtests", "passed"}}` from the run's reports.

    First writer wins, matching `run_corpus.load_results`: a `--resume` rerun
    appends a second report for the same shard and the earlier one is the run
    the published snapshot was taken from.
    """
    verdicts = {}
    for path in sorted(glob.glob(os.path.join(out_dir, "*.json"))):
        if os.path.basename(path) == "state.json":
            continue
        try:
            with open(path, encoding="utf-8") as fh:
                report = json.load(fh)
        except (OSError, ValueError):
            continue
        for result in report.get("results", []):
            test_id = result.get("test")
            if not test_id or test_id in verdicts:
                continue
            subtests = result.get("subtests") or []
            verdicts[test_id] = {
                "status": result.get("status", ""),
                "seconds": (result.get("duration") or 0) / 1000.0,
                "subtests": len(subtests),
                "passed": sum(1 for s in subtests if s.get("status") == "PASS"),
            }
    return verdicts


def score_of(status: str, subtests: int, passed: int) -> float:
    """The published number's per-id score — `run_corpus.py::score_reports`."""
    if subtests:
        return passed / subtests
    return 1.0 if status == "PASS" else 0.0


def unservable_reason(test_id: str):
    """Why a private static server cannot serve this id faithfully, or None."""
    base = test_id.split("?")[0]
    path = os.path.join(WPT_ROOT, base.lstrip("/"))
    if not os.path.exists(path):
        return "generated by wptserve (.any/.window), no file on disk"
    if ".sub." in base:
        return "needs .sub substitution"
    try:
        with open(path, encoding="utf-8", errors="replace") as fh:
            source = fh.read()
    except OSError:
        return "unreadable"
    if "testdriver.js" in source:
        return "needs testdriver (wptrunner message queue)"
    return None


#: `<script src=...>` of a test document — used to ask the cheapest possible
#: question about a hanging test before spending a browser on it: does the page
#: even have the helpers it loads? A test whose harness helper is not vendored
#: cannot finish under any ceiling, so it is not evidence about BUG-796 either
#: way, and a sample drawn without separating those two strata measures mostly
#: the vendoring gap.
_HELPER_RE = re.compile(r"""<script[^>]*\bsrc\s*=\s*["']?([^"'>\s]+)""", re.I)
_IFRAME_RE = re.compile(r"<iframe", re.I)
_WORKER_RE = re.compile(r"\bWorker\s*\(|SharedWorker|ServiceWorker")


def structural_blockers(test_id: str) -> set:
    """Reasons this test cannot complete that a longer ceiling would not lift.

    Source scan only, deliberately: it is a filter for choosing what to probe,
    not a verdict. `missing-helper` is the sharp one — the file the page loads
    is not in the checkout, so the harness never gets its `subsetTestByKey` /
    `idl_test` and sits waiting forever. `iframe`/`worker` are softer (the
    engine has neither a nested browsing context nor workers, but a test may
    still complete without ever reaching that part).
    """
    base = test_id.split("?")[0]
    path = os.path.join(WPT_ROOT, base.lstrip("/"))
    try:
        with open(path, encoding="utf-8", errors="replace") as fh:
            source = fh.read()
    except OSError:
        return {"unreadable"}
    tags = set()
    for src in _HELPER_RE.findall(source):
        target = (os.path.join(WPT_ROOT, src.lstrip("/")) if src.startswith("/")
                  else os.path.join(os.path.dirname(path), src))
        if not os.path.exists(target.split("?")[0]):
            tags.add("missing-helper")
    if _IFRAME_RE.search(source):
        tags.add("iframe")
    if _WORKER_RE.search(source):
        tags.add("worker")
    return tags


def missing_helpers(ids) -> collections.Counter:
    """Which unvendored `<script src>` the population is waiting on, by count."""
    counts = collections.Counter()
    for test_id in ids:
        base = test_id.split("?")[0]
        path = os.path.join(WPT_ROOT, base.lstrip("/"))
        try:
            with open(path, encoding="utf-8", errors="replace") as fh:
                source = fh.read()
        except OSError:
            continue
        for src in _HELPER_RE.findall(source):
            target = (os.path.join(WPT_ROOT, src.lstrip("/")) if src.startswith("/")
                      else os.path.join(os.path.dirname(path), src))
            if not os.path.exists(target.split("?")[0]):
                counts[src.split("?")[0]] += 1
    return counts


def census(manifest: dict, verdicts: dict) -> dict:
    """The population this audit is about, before a single browser is started."""
    longs = long_ids(manifest)
    executed = {tid: v for tid, v in verdicts.items() if tid in longs}
    modes = collections.Counter()
    fast, slow = [], []
    for tid, v in executed.items():
        if v["status"] not in ("TIMEOUT", "EXTERNAL-TIMEOUT"):
            continue
        if v["seconds"] < INTERNAL_CAP_S:
            modes["internal 10s cap (BUG-796)"] += 1
            fast.append(tid)
        else:
            modes["external wptrunner cap"] += 1
            slow.append(tid)
    reasons = collections.Counter()
    probeable = []
    for tid in fast:
        reason = unservable_reason(tid)
        if reason:
            reasons[reason] += 1
        else:
            probeable.append(tid)
    strata = collections.Counter()
    unblocked = []
    for tid in probeable:
        tags = structural_blockers(tid)
        if tags:
            for tag in tags:
                strata[tag] += 1
        else:
            strata["no blocker in source"] += 1
            unblocked.append(tid)
    return {
        "long_declared": len(longs),
        "long_executed": len(executed),
        "long_status": dict(collections.Counter(v["status"] for v in executed.values())),
        "timeout_modes": dict(modes),
        "fast": sorted(fast),
        "slow": sorted(slow),
        "probeable": sorted(probeable),
        "unblocked": sorted(unblocked),
        "strata": dict(strata),
        "missing_helpers": dict(missing_helpers(probeable).most_common(10)),
        "unservable": dict(reasons),
    }


