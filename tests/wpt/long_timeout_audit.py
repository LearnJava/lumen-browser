class _ArmHandler(http.server.SimpleHTTPRequestHandler):
    """Serves `tests/wpt/`; injects the repair shim when the arm asks for it.

    Two rewrites, both of which a plain file server would get wrong:
    `testharnessreport.js` carries wptserve's four `%%(...)s` placeholders and is
    a syntax error unserved through them, and arm B needs the shim ahead of the
    `testharness.js` include.
    """

    repair = False

    def log_message(self, fmt, *args):  # noqa: D102 - silence per-request logging
        pass

    def do_GET(self):  # noqa: N802 - name fixed by BaseHTTPRequestHandler
        path = self.translate_path(self.path.split("?")[0])
        if not os.path.isfile(path):
            return super().do_GET()
        try:
            with open(path, "rb") as fh:
                raw = fh.read()
        except OSError:
            self.send_error(404)
            return None
        text = raw.decode("utf-8", "replace")
        if path.replace("\\", "/").endswith("/resources/testharnessreport.js"):
            text = text % REPORT_ARGS
        elif self.repair and path.lower().endswith((".html", ".xht", ".xhtml", ".htm")):
            text = inject_shim(text)
        body = text.encode("utf-8")
        self.send_response(200)
        self.send_header("Content-Type", self.guess_type(path))
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)
        return None


def inject_shim(source: str) -> str:
    """Put `REPAIR_SHIM` immediately before the page's `testharness.js` include.

    A page with no such include is returned untouched: it is not a testharness
    test, so there is nothing for the shim to fix in time.
    """
    match = _TESTHARNESS_RE.search(source)
    if not match:
        return source
    return source[:match.start()] + REPAIR_SHIM + source[match.start():]


def start_server(repair: bool) -> tuple:
    """Serve `tests/wpt/` on a free port; returns (server, port)."""
    handler = type("_Arm", (_ArmHandler,), {"repair": repair})
    handler = functools.partial(handler, directory=WPT_ROOT)
    server = http.server.ThreadingHTTPServer(("127.0.0.1", 0), handler)
    server.daemon_threads = True
    threading.Thread(target=server.serve_forever, daemon=True).start()
    return server, server.server_address[1]


