import corpus_stats  # noqa: E402

#: Below this many seconds a TIMEOUT of a `long` id was cut off by the harness's
#: own 10 s default (slice 29 measured the two modes at 10.2 s and 65.0 s; the
#: gap between them is empty, 2 ids of 2 194). Above it the id hit wptrunner's
#: external ceiling, which BUG-796 does not touch.
INTERNAL_CAP_S = 13.0

#: Statuses the score treats as "the harness itself came back".
HARNESS_OK = frozenset({"OK", "PASS"})

#: What `StaticHandler` (wptserve) substitutes into `testharnessreport.js` for a
#: default run — read back off the live server by `route_audit.py` in slice 22,
#: not guessed. Arm B must keep `timeout_multiplier` at 1: the whole point is to
#: change the *declared* ceiling, not to hand every test more wall clock.
REPORT_ARGS = {"output": 0, "timeout_multiplier": 1,
               "explicit_timeout": "false", "debug": "false"}

#: Injected immediately before the page's own `testharness.js` include, so the
#: `Tests` singleton's constructor — which calls `test_timeout()` at parse time —
#: sees a working `content`. Reports how many metas it repaired on
#: `__lumen_repair_applied`, so a run can prove the arm did something rather
#: than assume it.
REPAIR_SHIM = """<script>
(function () {
  var fixed = 0;
  var metas = document.getElementsByTagName('meta');
  for (var i = 0; i < metas.length; i++) {
    var m = metas[i];
    if (m.content !== undefined) { continue; }
    try {
      Object.defineProperty(m, 'content', {
        configurable: true,
        get: (function (el) { return function () { return el.getAttribute('content'); }; })(m)
      });
      fixed++;
    } catch (e) { /* non-configurable: nothing this shim can do */ }
  }
  window.__lumen_repair_applied = fixed;
})();
</script>
"""

_TESTHARNESS_RE = re.compile(
    r"""<script[^>]*\bsrc\s*=\s*["']?[^"'>]*testharness\.js""", re.I)

#: `testharnessreport.js` ships the raw numeric codes, not their names — the
#: naming is `wptrunner`'s (`executors/base.py::TestharnessResultConverter`) and
#: happens on the runner side, which this audit bypasses. Decoding here rather
#: than comparing numbers keeps the buckets readable and, more importantly, keeps
#: `score_of` fed the same status strings the published number is scored from.
HARNESS_CODES = {0: "OK", 1: "ERROR", 2: "TIMEOUT", 3: "PRECONDITION_FAILED"}
SUBTEST_PASS = 0

RESULTS_GLOBAL = "__lumen_wpt_results"
STALE_GLOBAL = "__lumen_wpt_stale"
POLL_INTERVAL_S = 0.1

RESET_EXPRESSION = f"""(() => {{
  window.{RESULTS_GLOBAL} = undefined;
  window.{STALE_GLOBAL} = true;
}})()"""

POLL_EXPRESSION = f"""(() => {{
  if (window.{STALE_GLOBAL} === true) {{ return JSON.stringify({{k: "s"}}); }}
  if (window.{RESULTS_GLOBAL} !== undefined) {{
    return JSON.stringify({{k: "r", v: window.{RESULTS_GLOBAL},
                            fixed: window.__lumen_repair_applied}});
  }}
  return null;
}})()"""


