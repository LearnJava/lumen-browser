def print_census(data: dict) -> None:
    """The population table — printed by every mode, browser or not."""
    print(f"`timeout: long` ids in the manifest: {data['long_declared']}")
    print(f"executed by this run:                {data['long_executed']}")
    for status, count in sorted(data["long_status"].items(), key=lambda kv: -kv[1]):
        print(f"    {status:<22} {count}")
    print("TIMEOUTs by which ceiling stopped them:")
    for mode, count in sorted(data["timeout_modes"].items(), key=lambda kv: -kv[1]):
        print(f"    {mode:<30} {count}")
    print(f"of the {len(data['fast'])} cut off at 10 s, probeable here: {len(data['probeable'])}")
    for reason, count in sorted(data["unservable"].items(), key=lambda kv: -kv[1]):
        print(f"    not probeable: {reason:<45} {count}")
    print("of the probeable ones, what the source says stands in the way "
          "(tags overlap):")
    for tag, count in sorted(data["strata"].items(), key=lambda kv: -kv[1]):
        print(f"    {tag:<25} {count}")
    if data.get("missing_helpers"):
        print("unvendored helper scripts they load:")
        for src, count in sorted(data["missing_helpers"].items(), key=lambda kv: -kv[1]):
            print(f"    {src:<55} {count}")


def _selftest() -> int:
    """Pure-function checks — no browser, no server, no corpus."""
    failures = []

    def check(name, cond):
        if not cond:
            failures.append(name)

    check("score: subtest ratio", abs(score_of("TIMEOUT", 4, 1) - 0.25) < 1e-9)
    check("score: bare PASS", score_of("PASS", 0, 0) == 1.0)
    check("score: bare OK scores nothing", score_of("OK", 0, 0) == 0.0)

    page = '<meta name="timeout" content="long">\n<script src="/resources/testharness.js"></script>'
    injected = inject_shim(page)
    check("shim lands before the include",
          injected.index("__lumen_repair_applied") < injected.index("testharness.js"))
    check("shim keeps the meta", injected.index('name="timeout"') < injected.index("<script>"))
    check("no include, no shim", inject_shim("<p>hi</p>") == "<p>hi</p>")

    check("report placeholders substitute",
          "timeout_multiplier: 1" in ("setup({timeout_multiplier: %(timeout_multiplier)s})"
                                      % REPORT_ARGS))

    rows = {
        "/a": {"a": {"status": "TIMEOUT", "subtests": 2, "passed": 0},
               "b": {"status": "OK", "subtests": 2, "passed": 2}},
        "/b": {"a": {"status": "TIMEOUT", "subtests": 0, "passed": 0},
               "b": {"status": "CAP", "subtests": 0, "passed": 0}},
        "/c": {"a": {"status": "OK", "subtests": 2, "passed": 1},
               "b": {"status": "OK", "subtests": 2, "passed": 1}},
        "/d": {"a": {"status": "PROBE-ERROR"}, "b": {"status": "OK"}},
    }
    check("recovered", classify(rows["/a"])[0] == "recovered")
    check("still-timeout", classify(rows["/b"])[0] == "still-timeout")
    check("unchanged", classify(rows["/c"])[0] == "unchanged")
    check("probe-error excluded", classify(rows["/d"])[0] == "probe-error")

    proj = project(rows, population=300, corpus_ids=1000)
    check("projection divides by measured ids only", proj["measured"] == 3)
    check("projection scales the mean", abs(proj["projected_score"] - 100.0) < 0.05)
    check("projection in points", abs(proj["projected_points"] - 10.0) < 0.01)

    # A CAP in arm B is a timeout for classification but its score is still 0.
    check("cap scores zero", score_of("CAP", 0, 0) == 0.0)
    check("harness codes decode", HARNESS_CODES[2] == "TIMEOUT" and HARNESS_CODES[0] == "OK")
    check("blocker scan flags a missing helper",
          "missing-helper" in structural_blockers(
              "/encoding/legacy-mb-korean/euc-kr/euckr-decode-cseuckr.html?1-1000"))
    check("blocker scan flags an iframe",
          "iframe" in structural_blockers(
              "/encoding/legacy-mb-korean/euc-kr/euckr-decode-cseuckr.html?1-1000"))
    check("blocker scan on a missing file says so",
          structural_blockers("/nope/does-not-exist.html") == {"unreadable"})

    if failures:
        for name in failures:
            print(f"selftest FAILED: {name}", file=sys.stderr)
        return 1
    print(f"selftest OK ({18 - len(failures)} checks)")
    return 0


def main() -> int:
    """CLI entry point."""
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--binary", default=os.path.join(
        REPO_ROOT, "target", os.environ.get("LUMEN_PROFILE", "dev-release"), "lumen"))
    parser.add_argument("--out-dir", default=os.path.join(REPO_ROOT, ".tmp", "wpt-corpus"),
                        help="the corpus run's report directory (arm A's verdicts come "
                             "from the manifest+reports, the arms themselves are re-run)")
    parser.add_argument("--manifest", default=corpus_stats.DEFAULT_MANIFEST)
    parser.add_argument("--sample", type=int, default=40)
    parser.add_argument("--seed", type=int, default=796)
    parser.add_argument("--jobs", type=int, default=3)
    parser.add_argument("--cap", type=float, default=90.0,
                        help="wall-clock ceiling per arm (arm B's own ceiling is 65 s)")
    parser.add_argument("--stratum", choices=("all", "unblocked"), default="all",
                        help="`unblocked` samples only ids whose source shows no "
                             "structural reason to hang — the stratum where a wrong "
                             "ceiling could actually be the binding constraint")
    parser.add_argument("--census", action="store_true", help="population only, no browser")
    parser.add_argument("--json", help="write the full per-id table here")
    parser.add_argument("--selftest", action="store_true")
    args = parser.parse_args()

    if args.selftest:
        return _selftest()

    with open(args.manifest, encoding="utf-8") as fh:
        manifest = json.load(fh)
    verdicts = load_verdicts(args.out_dir)
    data = census(manifest, verdicts)
    print_census(data)
    if args.census:
        if args.json:
            with open(args.json, "w", encoding="utf-8") as fh:
                json.dump(data, fh, indent=1)
        return 0

    if not os.path.isfile(args.binary):
        print(f"lumen binary not found: {args.binary}", file=sys.stderr)
        return 1

    population = data["unblocked"] if args.stratum == "unblocked" else data["probeable"]
    rng = random.Random(args.seed)
    sample = rng.sample(population, min(args.sample, len(population)))
    print(f"\nprobing {len(sample)} of {len(population)} ({args.stratum}) on {args.jobs} browsers "
          f"(arm A: as served, arm B: meta.content repaired)\n")

    server_a, port_a = start_server(repair=False)
    server_b, port_b = start_server(repair=True)
    results = {}
    done = [0]

    def progress(test_id, row):
        done[0] += 1
        bucket = classify(row)[0]
        arm_a, arm_b = row["a"], row["b"]
        print(f"  [{done[0]:>3}/{len(sample)}] {bucket:<13} "
              f"A={arm_a.get('status'):<12}{arm_a.get('seconds', 0):5.1f}s  "
              f"B={arm_b.get('status'):<12}{arm_b.get('seconds', 0):5.1f}s  "
              f"fixed={arm_b.get('fixed')}  {test_id}", flush=True)

    async def drive():
        lock = asyncio.Lock()
        queue = list(sample)
        await asyncio.gather(*[
            worker(args.binary, port_a, port_b, queue, lock, args.cap, results, progress)
            for _ in range(max(1, args.jobs))])

    started = time.time()
    try:
        asyncio.run(drive())
    finally:
        server_a.shutdown()
        server_b.shutdown()

    corpus_ids = sum(1 for t, _c, _i in corpus_stats.iter_ids(manifest)
                     if t not in corpus_stats.NON_AUTOMATABLE_TYPES)
    proj = project(results, len(population), corpus_ids)
    print(f"\n{len(results)} ids probed in {(time.time() - started) / 60:.1f} min")
    for bucket, count in sorted(proj["buckets"].items(), key=lambda kv: -kv[1]):
        print(f"    {bucket:<15} {count}")
    print(f"\nmean score delta per probed id: {proj['mean_delta']:+.4f}")
    print(f"projected over {proj['population']} ids of the {args.stratum} stratum: "
          f"{proj['projected_score']:+.1f} score points "
          f"= {proj['projected_points']:+.4f} pass-rate points of {corpus_ids} ids")

    if args.json:
        with open(args.json, "w", encoding="utf-8") as fh:
            json.dump({"census": data, "sample": sample, "results": results,
                       "projection": proj}, fh, indent=1)
        print(f"wrote {args.json}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
