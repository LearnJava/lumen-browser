REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
WPT_ROOT = os.path.join(REPO_ROOT, "tests", "wpt")
sys.path[:0] = [REPO_ROOT, os.path.join(REPO_ROOT, "tools", "webdriver"),
                os.path.dirname(os.path.abspath(__file__))]

import corpus_stats  # noqa: E402
import missing_helper_audit as mha  # noqa: E402

#: The test CA `tests/wpt/certs/` — `wptserve`'s own, trusted by the browser only
#: through `LUMEN_EXTRA_CA_CERT`, never by the system store.
CERTS = os.path.join(WPT_ROOT, "certs")

#: Path the framing check serves from both arms. Not a file: it must exist in
#: whatever tree the audit is pointed at, and it must be trivial enough that
#: "did it lay out" has one answer.
PROBE_PATH = "/__lumen_tls_framing_probe__.html"

#: A width and height the default UA stylesheet cannot produce by accident, so
#: finding both in a layout dump proves the body arrived and was parsed. Same
#: trick as `verify_bug792_tls_eof_body.py`, which isolates the defect itself.
PROBE_PAGE = (b"<html><body><div style='width:333px;height:77px'></div>"
              b"</body></html>")

#: How an id is recognised as belonging to the https corpus. `wptserve` decides
#: this by filename, and so does the manifest — `.https.` anywhere in the path
#: makes the test load over TLS. This is the same rule BUG-792 counted its 7 190
#: with, kept identical on purpose: a different rule would produce a different
#: denominator and the two numbers would stop being comparable.
def is_https_id(test_id: str) -> bool:
    """True if `wptserve` would serve this id over TLS."""
    return ".https." in test_id.split("?")[0]


