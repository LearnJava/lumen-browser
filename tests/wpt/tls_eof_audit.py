def print_census(data: dict) -> None:
    """The population table — printed by every mode, browser or not."""
    print(f"automatable ids in the manifest:   {data['automatable_ids']}")
    print(f"served over https by wptserve:     {data['https_ids']} "
          f"({100.0 * data['https_ids'] / max(1, data['automatable_ids']):.1f} %)")
    for test_type, count in sorted(data["https_by_type"].items(), key=lambda kv: -kv[1]):
        print(f"    {test_type:<22} {count}")
    print(f"of them executed by this run:      {data['https_executed']}, "
          f"holding {data['https_score_held']} score points today")
    for status, count in sorted(data["https_executed_status"].items(), key=lambda kv: -kv[1]):
        print(f"    {status:<22} {count}")
    print(f"probeable by a private server:     {len(data['probeable'])}")
    for reason, count in sorted(data["unservable"].items(), key=lambda kv: -kv[1]):
        print(f"    not probeable: {reason:<48} {count}")


def _selftest() -> int:
    """Pure-function checks — no browser, no network, no corpus."""
    failures = []

    def check(name, cond):
        if not cond:
            failures.append(name)

    check("https by filename", is_https_id("/a/b.https.any.html"))
    check("https survives a query", is_https_id("/a/b.https.html?x=.plain."))
    check("query alone does not make a test https", not is_https_id("/a/b.html?y=.https."))
    check("plain id is not https", not is_https_id("/a/b.window.html"))

    # The scoring rule and the buckets are the published ones, borrowed whole
    # from slice 31 so the two slices' numbers are in the same unit.
    check("score: subtest ratio", abs(mha.score_of("TIMEOUT", 4, 1) - 0.25) < 1e-9)
    check("score: bare PASS", mha.score_of("PASS", 0, 0) == 1.0)
    check("not-replaced counts as dead", "NOT-REPLACED" in mha.DEAD_STATUSES)

    rows = {
        # The shape this audit expects on a blocked id: arm A never gets a
        # document, arm B runs the test.
        "/a": {"a": {"status": "NOT-REPLACED", "subtests": 0, "passed": 0},
               "b": {"status": "OK", "subtests": 4, "passed": 3}},
        # BUG-792 hides the document, not necessarily a passing test.
        "/b": {"a": {"status": "NOT-REPLACED", "subtests": 0, "passed": 0},
               "b": {"status": "OK", "subtests": 2, "passed": 0}},
        "/c": {"a": {"status": "NOT-REPLACED", "subtests": 0, "passed": 0},
               "b": {"status": "NOT-REPLACED", "subtests": 0, "passed": 0}},
    }
    check("revived", mha.classify(rows["/a"])[0] == "revived")
    check("revived onto zero is still revived", mha.classify(rows["/b"])[0] == "revived")
    check("dead in both arms", mha.classify(rows["/c"])[0] == "still-dead")

    proj = mha.project(rows, population=1000, corpus_ids=10000)
    check("projection divides by measured ids only", proj["measured"] == 3)
    check("projection scales the mean", abs(proj["projected_score"] - 250.0) < 0.5)
    check("projection in points", abs(proj["projected_points"] - 2.5) < 0.01)

    # A framing check that says nothing must not read as a pass: only "arm B laid
    # it out AND arm A did not" is the state in which the measurement is valid.
    for arm_a, arm_b, want in ((False, True, True), (True, True, False),
                               (False, False, False), (True, False, False)):
        check(f"framing verdict A={arm_a} B={arm_b}", framing_ok(arm_a, arm_b) is want)

    if failures:
        for name in failures:
            print(f"selftest FAILED: {name}", file=sys.stderr)
        return 1
    print("selftest OK (17 checks)")
    return 0


def main() -> int:
    """CLI entry point."""
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--binary", default=os.path.join(
        REPO_ROOT, "target", os.environ.get("LUMEN_PROFILE", "dev-release"), "lumen"))
    parser.add_argument("--out-dir", default=os.path.join(REPO_ROOT, ".tmp", "wpt-corpus"),
                        help="the corpus run's report directory (for what the https "
                             "ids score today; the arms themselves are re-run)")
    parser.add_argument("--manifest", default=corpus_stats.DEFAULT_MANIFEST)
    parser.add_argument("--sample", type=int, default=60)
    parser.add_argument("--seed", type=int, default=792)
    parser.add_argument("--jobs", type=int, default=3)
    parser.add_argument("--cap", type=float, default=30.0,
                        help="wall-clock ceiling per arm. A page that wedges the "
                             "browser answers nothing, in either arm, and costs this "
                             "twice; `testharness.js` itself gives up at 10 s (60 s "
                             "for `timeout: long`, and BUG-796 currently makes even "
                             "those 10 s), so 30 s is past the point where a live "
                             "page still has something to report")
    parser.add_argument("--stale-cap", type=float, default=6.0,
                        help="how long an arm may sit on the outgoing document "
                             "before the navigation counts as never landed; arm A "
                             "spends this on every id by construction, so it sets the "
                             "floor price of the whole run")
    parser.add_argument("--prefix", default="",
                        help="sample only ids under this path, and project over that "
                             "stratum's own size — the population is heavy-tailed "
                             "(slice 31)")
    parser.add_argument("--census", action="store_true", help="population only, no browser")
    parser.add_argument("--no-check-framing", action="store_true",
                        help="skip the precondition that arm A actually reproduces "
                             "BUG-792 on this build; only for debugging the harness")
    parser.add_argument("--json", help="write the full per-id table here")
    parser.add_argument("--selftest", action="store_true")
    args = parser.parse_args()

    if args.selftest:
        return _selftest()

    with open(args.manifest, encoding="utf-8") as fh:
        manifest = json.load(fh)
    verdicts = mha.load_verdicts(args.out_dir)
    data = census(manifest, verdicts)
    print_census(data)
    if args.census:
        if args.json:
            with open(args.json, "w", encoding="utf-8") as fh:
                json.dump(data, fh, indent=1)
        return 0

    if not os.path.isfile(args.binary):
        print(f"lumen binary not found: {args.binary}", file=sys.stderr)
        return 1

    population = data["probeable"]
    if args.prefix:
        population = [tid for tid in population if tid.startswith(args.prefix)]
        if not population:
            print(f"no probeable id under {args.prefix}", file=sys.stderr)
            return 1

    server_a, port_a = start_tls_server(clean_shutdown=False)
    server_b, port_b = start_tls_server(clean_shutdown=True)
    framing = None
    try:
        if not args.no_check_framing:
            framing = check_framing(args.binary, port_a, port_b)
            print(f"\nframing check: arm A (abrupt) "
                  f"{'LAID OUT' if framing['a'] else 'LOST'}, "
                  f"arm B (close_notify) {'LAID OUT' if framing['b'] else 'LOST'}")
            for arm in ("a", "b"):
                if framing[f"{arm}_stderr"]:
                    print(f"    arm {arm}: {framing[f'{arm}_stderr'].splitlines()[0]}")
            if not framing["ok"]:
                print("the arms do not differ the way BUG-792 says they should — "
                      "nothing measured here would mean what it says", file=sys.stderr)
                return 2

        rng = random.Random(args.seed)
        sample = rng.sample(population, min(args.sample, len(population)))
        print(f"\nprobing {len(sample)} of {len(population)} https ids on {args.jobs} "
              f"browsers (arm A: no close_notify, arm B: close_notify)\n")

        results = {}
        done = [0]

        def progress(test_id, row):
            done[0] += 1
            bucket = mha.classify(row)[0]
            arm_a, arm_b = row["a"], row["b"]
            print(f"  [{done[0]:>3}/{len(sample)}] {bucket:<11} "
                  f"A={arm_a.get('status'):<12}{arm_a.get('seconds', 0):5.1f}s "
                  f"{arm_a.get('passed', 0)}/{arm_a.get('subtests', 0)}  "
                  f"B={arm_b.get('status'):<12}{arm_b.get('seconds', 0):5.1f}s "
                  f"{arm_b.get('passed', 0)}/{arm_b.get('subtests', 0)}  {test_id}",
                  flush=True)

        mha.disable_ws_keepalive()
        env = browser_env()

        async def drive():
            lock = asyncio.Lock()
            queue = list(sample)
            await asyncio.gather(*[
                mha.worker(args.binary, port_a, port_b, queue, lock, args.cap,
                           results, progress, scheme="https", env=env,
                           stale_cap=args.stale_cap, order=("b", "a"))
                for _ in range(max(1, args.jobs))])

        started = time.time()
        asyncio.run(drive())
    finally:
        server_a.shutdown()
        server_b.shutdown()

    corpus_ids = data["automatable_ids"]
    proj = mha.project(results, len(population), corpus_ids)
    print(f"\n{len(results)} ids probed in {(time.time() - started) / 60:.1f} min")
    for bucket, count in sorted(proj["buckets"].items(), key=lambda kv: -kv[1]):
        print(f"    {bucket:<15} {count}")
    dead_a = sum(1 for row in results.values()
                 if (row.get("a") or {}).get("status") in mha.DEAD_STATUSES)
    print(f"\narm A produced no document on {dead_a} of {len(results)} ids "
          f"(BUG-792 says it should be all of them)")
    capped_b = sum(1 for row in results.values()
                   if (row.get("b") or {}).get("status") == "CAP")
    print(f"arm B hit the {args.cap:.0f}s cap on {capped_b} ids — a page that answers "
          f"nothing wedges both arms alike, so those are counted as no verdict, not as "
          f"a zero the fix would have to earn")
    print(f"subtests seen: arm A {proj['subtests_a']}, arm B {proj['subtests_b']}")
    print(f"\nmean score delta per probed id: {proj['mean_delta']:+.4f}")
    print(f"projected over {proj['population']} probeable https ids: "
          f"{proj['projected_score']:+.1f} score points "
          f"= {proj['projected_points']:+.4f} pass-rate points of {corpus_ids} ids")
    unmeasured = data["https_ids"] - len(data["probeable"])
    print(f"outside the probed stratum: {unmeasured} https ids "
          f"(generated by wptserve, reftest, testdriver) — blocked the same, unmeasured here")

    if args.json:
        with open(args.json, "w", encoding="utf-8") as fh:
            json.dump({"census": data, "framing": framing, "sample": sample,
                       "results": results, "projection": proj}, fh, indent=1)
        print(f"wrote {args.json}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
