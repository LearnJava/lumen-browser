#!/usr/bin/env python3
"""WPT-RUN-5 slice 32: what does BUG-792 cost the number, as opposed to reach?

[BUG-792](../../bugs/BUG-792-OPEN.md) states its reach and states it correctly:
`wptserve` answers close-delimited over TLS and never sends `close_notify`, our
body reader throws away everything it read on that error, so **7 190 automatable
manifest ids (10.6 % of the corpus) carry no document at all** — 0 harness OK and
0 subtests out of 635 executed `.https.` tests in the WPT-RUN-5 Linux half.

Reach is not price. Slices 30 and 31 measured that difference twice and both
times the price was two orders of magnitude below the reach ([BUG-796](
../../bugs/BUG-796-OPEN.md): 10.1 % of the corpus blocked, +0.10 pass-rate points
once unblocked). An id that never gets its document costs the figure only what it
*would have scored* with the document, and nothing so far has asked those 7 190
ids that question — they have never once run with a body.

This audit asks it directly, per test, with an A/B on the same binary against two
private TLS servers that differ in exactly one byte-level detail:

* **arm A** — EOF-framed response (no `Content-Length`, `Connection: close`), the
  socket then closed with no TLS shutdown. That is `wptserve`'s framing, and what
  the corpus run gets on every `.https.` id today.
* **arm B** — the same bytes, same headers, same EOF framing, `close_notify` sent
  before the close.

Arm B is not "some other server": it is the same response, ended politely. Since
the whole content of the fix is "treat `UnexpectedEof` on EOF framing as the end
of the body", the bytes the engine holds in arm B are exactly the bytes a fixed
engine would hold in arm A. The delta between the arms, scored by the published
rule, is therefore the price of BUG-792 in pass-rate points.

The framing is checked, not assumed: `--check-framing` (on by default) serves one
marker page from both arms and refuses to run unless arm A loses it and arm B
lays it out. Without that, an arm A that quietly worked would report a null result
that reads as "BUG-792 is free".

What this deliberately does not do, and why:

* **It does not run `wptserve`.** The corpus run owns the pinned ports and a
  second runner would either fight it for them or inherit a dead run's
  substituted harness options through the `StaticHandler` freeze (`CLAUDE.md`).
  Pages are served privately, the way `missing_helper_audit.py` does — whose
  server, `.sub.` substitution and BiDi scoring loop this reuses.
* **It does not write into `tests/wpt/`.** Same reason as slice 31: the corpus
  run reads test files off the doc root per request, and changing the tree
  mid-run hands later shards a different corpus than earlier ones.
* **It scores only ids with a file on disk.** 4 556 of the 7 190 have one; the
  other 2 634 are `.any.js`/`.window.js` ids whose html is generated by
  `wptserve` at request time, and generating them here would measure our wrapper
  rather than the engine. They are blocked by BUG-792 just the same — the census
  names them in ids so the unmeasured part is stated rather than implied.

Usage (from repo root, venv per tests/wpt/README.md):

    <venv>/python tests/wpt/tls_eof_audit.py --census
    <venv>/python tests/wpt/tls_eof_audit.py --sample 60 --jobs 3 --json OUT
    <venv>/python tests/wpt/tls_eof_audit.py --selftest
"""

