# the two arms
# --------------------------------------------------------------------------- #

class EofHandler(mha.ArmHandler):
    """Serves `tests/wpt/` close-delimited: no `Content-Length`, ever.

    `wptserve` frames a large share of its responses this way (RFC 7230 §3.3.3
    item 7) and the engine supports it — the defect is not the framing, it is
    what happens at the end of the connection, which the *server* decides (see
    `TlsServer.clean_shutdown`). Both arms answer identically down to the byte;
    keeping `Content-Length` off in both is what makes that true.
    """

    protocol_version = "HTTP/1.1"

    def do_GET(self):  # noqa: N802 - name fixed by BaseHTTPRequestHandler
        site_path = self.path.split("?")[0]
        if site_path == PROBE_PATH:
            self._respond(200, PROBE_PAGE, "text/html")
            return None
        rendered = self.render(site_path)
        if rendered is None:
            self._respond(404, b"not found\n", "text/plain")
            return None
        body, content_type = rendered
        self._respond(200, body, content_type)
        return None

    def _respond(self, code: int, body: bytes, content_type: str) -> None:
        """Status line, headers, body — close-delimited, connection then dies."""
        self.send_response(code)
        self.send_header("Content-Type", content_type)
        # `Connection: close` also sets `close_connection`, so the server reaches
        # `shutdown_request` after this response — which is where the arms differ.
        self.send_header("Connection", "close")
        self.end_headers()
        try:
            self.wfile.write(body)
        except OSError:
            pass  # the browser gave up on this subresource; not our verdict

    def setup(self) -> None:
        """Do the TLS handshake in this connection's own thread.

        `socketserver` calls `get_request` on the accept loop, so a handshake
        started there stalls every other connection behind it — and a browser
        that abandons a subresource mid-handshake is routine in this population.
        """
        self.connection = self.request
        try:
            self.connection.do_handshake()
        except OSError:
            pass  # `rfile.readline()` below then reads nothing and the thread ends
        super().setup()


class TlsServer(http.server.ThreadingHTTPServer):
    """Threading HTTPS server whose *shutdown* is the experimental variable.

    `clean_shutdown = False` (arm A) closes the socket with no TLS shutdown at
    all, which is what `wptserve` does and what `rustls` reports as
    `UnexpectedEof`; `True` (arm B) calls `unwrap()` first, which sends
    `close_notify`. Python's `ssl` never sends one on plain `close()`, so the
    default really is the abrupt case rather than a polite one by accident —
    `--check-framing` proves it against the engine rather than trusting this
    paragraph.
    """

    daemon_threads = True
    clean_shutdown = False

    def __init__(self, address, handler, context):
        """Bind `address`; `context` wraps every accepted connection."""
        self.ssl_context = context
        super().__init__(address, handler)

    def get_request(self):
        """Accept and wrap; the handshake itself is deferred to `setup`."""
        sock, addr = super().get_request()
        return self.ssl_context.wrap_socket(sock, server_side=True,
                                            do_handshake_on_connect=False), addr

    def shutdown_request(self, request):
        """End the TLS session politely or not at all — the arms' one difference."""
        if self.clean_shutdown:
            try:
                request = request.unwrap()   # sends close_notify
            except OSError:
                pass  # already gone; nothing to say goodbye to
        super().shutdown_request(request)


def start_tls_server(clean_shutdown: bool) -> tuple:
    """Serve `tests/wpt/` over TLS on a free port; returns (server, port)."""
    context = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
    context.load_cert_chain(os.path.join(CERTS, "host-cert.pem"),
                            os.path.join(CERTS, "host-key.pem"))
    handler = type("_TlsArm", (EofHandler,), {"cache": None})
    handler_partial = functools.partial(handler, directory=WPT_ROOT)
    server = TlsServer(("127.0.0.1", 0), handler_partial, context)
    server.clean_shutdown = clean_shutdown
    handler.port = server.server_address[1]
    threading.Thread(target=server.serve_forever, daemon=True).start()
    return server, server.server_address[1]


def browser_env() -> dict:
    """This process's environment plus the test CA the arms present."""
    return dict(os.environ, LUMEN_EXTRA_CA_CERT=os.path.join(CERTS, "ca-cert.pem"))


def framing_ok(arm_a_laid_out: bool, arm_b_laid_out: bool) -> bool:
    """Is the A/B valid at all — did arm A reproduce BUG-792 and arm B escape it?

    Both other outcomes are disqualifying, not merely surprising: two laid-out
    arms mean the abrupt close is not reaching the engine (nothing to measure,
    and a zero delta would read as "BUG-792 is free"), two lost ones mean arm B
    is broken for a reason of its own.
    """
    return arm_b_laid_out and not arm_a_laid_out


def check_framing(binary: str, port_a: int, port_b: int, timeout: float = 120) -> dict:
    """Prove arm A reproduces BUG-792 and arm B does not, on this build.

    Runs the marker page through `--dump-layout` on both ports. A run where arm A
    quietly succeeded would measure nothing and report it as "BUG-792 is free",
    which is the one wrong answer this audit could produce, so it is a
    precondition rather than a diagnostic.
    """
    out = {}
    for arm, port in (("a", port_a), ("b", port_b)):
        url = f"https://127.0.0.1:{port}{PROBE_PATH}"
        proc = subprocess.run([binary, "--dump-layout", url], cwd=REPO_ROOT,
                              env=browser_env(), capture_output=True, text=True,
                              timeout=timeout, check=False)
        out[arm] = "333" in proc.stdout and "77" in proc.stdout
        out[f"{arm}_stderr"] = "\n".join(
            line.strip()[:160] for line in (proc.stderr or "").splitlines()
            if "error" in line.lower() or "ошибка" in line.lower())[:600]
    out["ok"] = framing_ok(out["a"], out["b"])
    return out


