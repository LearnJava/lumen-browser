def census(manifest: dict, verdicts: dict) -> dict:
    """The https population and what it scores today, before a browser starts."""
    by_type = collections.Counter()
    ids = []
    total_automatable = 0
    for test_type, _category, test_id in corpus_stats.iter_ids(manifest):
        if test_type in corpus_stats.NON_AUTOMATABLE_TYPES:
            continue
        total_automatable += 1
        if not is_https_id(test_id):
            continue
        by_type[test_type] += 1
        ids.append((test_type, test_id))

    executed = 0
    held = 0.0
    executed_status = collections.Counter()
    for _type, test_id in ids:
        verdict = verdicts.get(test_id)
        if not verdict:
            continue
        executed += 1
        executed_status[verdict["status"]] += 1
        held += mha.score_of(verdict["status"], verdict["subtests"], verdict["passed"])

    probeable, unservable = [], collections.Counter()
    for test_type, test_id in ids:
        if test_type != "testharness":
            unservable[f"not testharness ({test_type})"] += 1
            continue
        reason = mha.unservable_reason(test_id)
        if reason:
            unservable[reason] += 1
        else:
            probeable.append(test_id)

    return {
        "automatable_ids": total_automatable,
        "https_ids": len(ids),
        "https_by_type": dict(by_type),
        "https_executed": executed,
        "https_executed_status": dict(executed_status.most_common(8)),
        "https_score_held": round(held, 2),
        "probeable": sorted(probeable),
        "unservable": dict(unservable),
    }


